<?php
declare(strict_types=1);
date_default_timezone_set('Asia/Tehran');
$root = dirname(__DIR__);
$outputPath = $root . '/context.md';
$dataRoot = $root . '/data';

function readJsonFile(string $path): array {
    $contents = file_get_contents($path);
    if ($contents === false) throw new RuntimeException("Could not read: {$path}");
    $data = json_decode($contents, true, 512, JSON_THROW_ON_ERROR);
    if (!is_array($data)) throw new RuntimeException("Expected a JSON object: {$path}");
    return $data;
}
function jsonFiles(string $directory): array {
    if (!is_dir($directory)) return [];
    $files = [];
    $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($directory, FilesystemIterator::SKIP_DOTS));
    foreach ($iterator as $file) if ($file->isFile() && strtolower($file->getExtension()) === 'json') $files[] = $file->getPathname();
    sort($files, SORT_NATURAL | SORT_FLAG_CASE);
    return $files;
}
function relativePath(string $path, string $root): string {
    return ltrim(str_replace('\\', '/', substr($path, strlen($root))), '/');
}
function firstString(array $data, array $keys, string $fallback): string {
    foreach ($keys as $key) if (isset($data[$key]) && is_string($data[$key]) && trim($data[$key]) !== '') return trim($data[$key]);
    return $fallback;
}
function collectStrings(mixed $value): array {
    if (!is_array($value)) return [];
    $result = [];
    foreach ($value as $item) {
        if (is_string($item) && trim($item) !== '') $result[] = trim($item);
        elseif (is_array($item)) $result = array_merge($result, collectStrings($item));
    }
    return $result;
}
function markdownList(array $items): array {
    $items = array_values(array_unique(array_filter(array_map('trim', $items), static fn ($v) => $v !== '')));
    natcasesort($items);
    return array_map(static fn ($item) => '- ' . $item, $items);
}
function loadEntries(string $directory, string $root): array {
    $entries = [];
    foreach (jsonFiles($directory) as $file) {
        $data = readJsonFile($file);
        $label = firstString($data, ['word', 'phrase', 'collocation', 'idiom', 'title', 'term'], pathinfo($file, PATHINFO_FILENAME));
        $meanings = [];
        foreach (($data['meanings'] ?? []) as $meaning) {
            if (is_array($meaning) && isset($meaning['meaning']) && is_string($meaning['meaning'])) $meanings[] = trim($meaning['meaning']);
        }
        foreach (($data['parts_of_speech'] ?? []) as $part) {
            if (!is_array($part)) continue;
            $pos = firstString($part, ['part_of_speech'], '');
            foreach (($part['meanings'] ?? []) as $meaning) {
                if (is_array($meaning) && isset($meaning['meaning']) && is_string($meaning['meaning'])) $meanings[] = ($pos !== '' ? $pos . ': ' : '') . trim($meaning['meaning']);
            }
        }
        $entries[] = ['label' => $label, 'meanings' => array_values(array_unique($meanings)), 'tags' => collectStrings($data['tags'] ?? []), 'source' => relativePath($file, $root), 'data' => $data];
    }
    usort($entries, static fn (array $a, array $b): int => strcasecmp($a['label'], $b['label']));
    return $entries;
}
function renderEntries(string $heading, array $entries): array {
    $lines = ['## ' . $heading, ''];
    if ($entries === []) return array_merge($lines, ['_No entries registered yet._', '']);
    foreach ($entries as $entry) {
        $lines[] = '### ' . $entry['label'];
        foreach ($entry['meanings'] as $meaning) $lines[] = '- ' . $meaning;
        if ($entry['meanings'] === [] && $entry['tags'] !== []) $lines[] = '- **Tags:** ' . implode(', ', $entry['tags']);
        $lines[] = '<!-- source: ' . $entry['source'] . ' -->';
        $lines[] = '';
    }
    return $lines;
}
try {
    $words = loadEntries($dataRoot . '/words', $root);
    $phrasalVerbs = loadEntries($dataRoot . '/phrasal_verbs', $root);
    $collocations = loadEntries($dataRoot . '/collocations', $root);
    $idioms = loadEntries($dataRoot . '/idioms', $root);
    $grammar = loadEntries($dataRoot . '/grammar', $root);
    $collocationSet = [];
    foreach ($words as $word) foreach (($word['data']['parts_of_speech'] ?? []) as $part) foreach (($part['meanings'] ?? []) as $meaning) foreach (($meaning['collocations'] ?? []) as $collocation) {
        if (is_string($collocation) && trim($collocation) !== '') $collocationSet[mb_strtolower(trim($collocation))] = trim($collocation);
    }
    foreach ($collocations as $entry) $collocationSet[mb_strtolower($entry['label'])] = $entry['label'];
    $materials = [];
    $materialsFile = $dataRoot . '/materials.json';
    if (is_file($materialsFile)) $materials = readJsonFile($materialsFile);
    ksort($materials, SORT_NATURAL | SORT_FLAG_CASE);

    $lines = [
        '# English Learning Context', '',
        '<!-- Automatically generated by scripts/context.php. Do not edit manually. -->', '',
        'This file is a machine-readable index of material recorded in this repository. Use it to understand what has been studied when generating personalised reading texts. It records repository entries; it does not prove that every item is mastered or can be recalled without help.', '',
        '## Inventory', '',
        '- Words: ' . count($words),
        '- Phrasal verbs: ' . count($phrasalVerbs),
        '- Collocations (including those embedded in word entries): ' . count($collocationSet),
        '- Idioms: ' . count($idioms),
        '- Grammar lessons: ' . count($grammar),
        '- Review-registered Markdown materials: ' . count($materials), ''
    ];
    $lines = array_merge($lines, renderEntries('Words', $words), renderEntries('Phrasal Verbs', $phrasalVerbs));
    $lines[] = '## Collocations'; $lines[] = '';
    $lines = array_merge($lines, markdownList(array_values($collocationSet))); $lines[] = '';
    $lines = array_merge($lines, renderEntries('Idioms', $idioms));
    $lines[] = '## Grammar Lessons'; $lines[] = '';
    if ($grammar === []) $lines[] = '_No grammar lessons registered yet._';
    foreach ($grammar as $lesson) {
        $lines[] = '### ' . $lesson['label'];
        if ($lesson['tags'] !== []) $lines[] = '- **Topics:** ' . implode(', ', $lesson['tags']);
        $headings = [];
        foreach (($lesson['data']['explanation'] ?? []) as $section) if (is_array($section) && isset($section['heading']) && is_string($section['heading'])) $headings[] = trim($section['heading']);
        if ($headings !== []) $lines[] = '- **Sections:** ' . implode('; ', $headings);
        $lines[] = '<!-- source: ' . $lesson['source'] . ' -->'; $lines[] = '';
    }
    $lines[] = '## Materials in the Review Registry'; $lines[] = '';
    if ($materials === []) $lines[] = '_No review materials registered yet._';
    foreach ($materials as $path => $timestamp) $lines[] = '- ' . $path . ' — last reviewed: ' . (is_string($timestamp) ? $timestamp : 'unknown');
    $lines = array_merge($lines, ['', '## Interpretation Notes', '',
        '- An item appearing here means it exists in repository data, not necessarily that it is fully mastered.',
        '- Word senses and grammar topics come from stored entries; no CEFR level is inferred unless the source data explicitly provides one.',
        '- Empty categories are intentional and will be populated automatically when matching data entries are added.', '']);
    if (file_put_contents($outputPath, rtrim(implode("\n", $lines)) . "\n") === false) throw new RuntimeException('Could not write context.md');
    printf("Updated context.md: %d words, %d phrasal verbs, %d collocations, %d idioms, %d grammar lessons.\n", count($words), count($phrasalVerbs), count($collocationSet), count($idioms), count($grammar));
} catch (Throwable $exception) {
    fwrite(STDERR, $exception->getMessage() . "\n");
    exit(1);
}
