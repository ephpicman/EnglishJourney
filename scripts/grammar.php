<?php

declare(strict_types=1);

/**
 * Render data/grammar JSON entries to Markdown pages in grammar/.
 * Run from any working directory: php scripts/grammar.php
 */

$root = dirname(__DIR__);
$dataGrammarRoot = $root . '/data/grammar';
$grammarRoot = $root . '/grammar';
$indexFile = $root . '/grammar.md';
$generatedMarker = '<!-- This file is generated by scripts/grammar.php. Do not edit it manually. -->';

$categories = [
    'tenses-aspect' => 'Verb Tenses and Aspect',
    'modality' => 'Modal Verbs and Modality',
    'conditionals' => 'Conditionals and Hypothetical Meaning',
    'passive-causative' => 'Passive Voice and Causative Structures',
    'reported-speech' => 'Reported Speech and Reporting Structures',
    'clause-structure' => 'Clause Structure and Complex Sentences',
    'verb-patterns' => 'Verb Patterns and Non-finite Forms',
    'word-order-emphasis' => 'Word Order, Inversion and Emphasis',
    'nouns-determiners' => 'Noun Phrases and Determiners',
    'adjectives-adverbs' => 'Adjectives, Adverbs and Comparison',
    'prepositions' => 'Prepositions and Prepositional Structures',
    'questions-negation' => 'Questions, Negation and Responses',
    'linking-structures' => 'Coordination, Subordination and Linking',
    'agreement-cohesion' => 'Agreement, Reference and Cohesion',
    'register-choices' => 'Advanced Grammatical Choices and Register',
];

/** Write only when generated content differs. */
function writeIfChanged(string $path, string $content): bool
{
    if (is_file($path)) {
        $existing = file_get_contents($path);

        if ($existing === false) {
            fwrite(STDERR, "Could not read existing file: {$path}\n");
            return false;
        }

        if ($existing === $content) {
            return true;
        }
    }

    $directory = dirname($path);

    if (!is_dir($directory) && !mkdir($directory, 0775, true) && !is_dir($directory)) {
        fwrite(STDERR, "Could not create directory: {$directory}\n");
        return false;
    }

    return file_put_contents($path, $content, LOCK_EX) !== false;
}

/** Normalise scalar text for Markdown output. */
function textValue(mixed $value): string
{
    if (!is_string($value) && !is_numeric($value)) {
        return '';
    }

    return trim(str_replace(["\r\n", "\r"], "\n", (string) $value));
}

/** Append a heading and paragraph when the value is non-empty. */
function appendText(array &$lines, string $heading, mixed $value, int $level = 2): void
{
    $text = textValue($value);

    if ($text === '') {
        return;
    }

    $lines[] = str_repeat('#', $level) . ' ' . $heading;
    $lines[] = '';
    $lines[] = $text;
    $lines[] = '';
}

/** Append a bullet list when it contains non-empty strings. */
function appendNotes(array &$lines, mixed $notes, string $heading = 'Notes'): void
{
    if (!is_array($notes)) {
        return;
    }

    $items = [];

    foreach ($notes as $note) {
        $note = textValue($note);

        if ($note !== '') {
            $items[] = '- ' . $note;
        }
    }

    if ($items !== []) {
        $lines[] = '**' . $heading . '**';
        $lines[] = '';
        array_push($lines, ...$items);
        $lines[] = '';
    }
}

/** Render each example with its exact sentence and British English IPA. */
function appendExamples(array &$lines, mixed $examples): void
{
    if (!is_array($examples) || $examples === []) {
        return;
    }

    foreach ($examples as $example) {
        if (!is_array($example)) {
            continue;
        }

        $sentence = textValue($example['text'] ?? '');
        $ipa = textValue($example['pronunciation']['uk'] ?? '');

        if ($sentence === '') {
            continue;
        }

        $lines[] = '- ' . $sentence;

        if ($ipa !== '') {
            $lines[] = '  - **UK IPA:** ' . $ipa;
        }

        appendNotes($lines, $example['notes'] ?? [], 'Example notes');
    }

    $lines[] = '';
}

/** Validate the entry structure before rendering. */
function validateEntry(mixed $entry, string $file): array
{
    $requiredKeys = [
        'type', 'title', 'tags', 'explanation',
        'forms', 'usage', 'common_mistakes', 'notes',
    ];

    if (!is_array($entry)) {
        throw new RuntimeException("Entry must be a JSON object: {$file}");
    }

    $actualKeys = array_keys($entry);
    sort($actualKeys);
    $expectedKeys = $requiredKeys;
    sort($expectedKeys);

    if ($actualKeys !== $expectedKeys) {
        throw new RuntimeException("Unexpected root fields or missing fields in: {$file}");
    }

    if ($entry['type'] !== 'grammar' || !is_string($entry['title']) || trim($entry['title']) === '') {
        throw new RuntimeException("Invalid type or title in: {$file}");
    }

    foreach (['tags', 'explanation', 'forms', 'usage', 'common_mistakes', 'notes'] as $field) {
        if (!is_array($entry[$field])) {
            throw new RuntimeException("Field '{$field}' must be an array in: {$file}");
        }
    }

    foreach (['explanation', 'forms', 'usage', 'common_mistakes'] as $field) {
        foreach ($entry[$field] as $item) {
            if (!is_array($item)) {
                throw new RuntimeException("Invalid item in '{$field}' in: {$file}");
            }
        }
    }

    foreach (array_merge($entry['forms'], $entry['usage']) as $item) {
        $examples = $item['examples'] ?? [];

        if (!is_array($examples)) {
            throw new RuntimeException("Examples must be an array in: {$file}");
        }

        foreach ($examples as $example) {
            if (
                !is_array($example)
                || !is_string($example['text'] ?? null)
                || trim($example['text']) === ''
                || !is_array($example['pronunciation'] ?? null)
                || !is_string($example['pronunciation']['uk'] ?? null)
                || trim($example['pronunciation']['uk']) === ''
                || !is_array($example['notes'] ?? null)
            ) {
                throw new RuntimeException("Invalid example or missing UK IPA in: {$file}");
            }
        }
    }

    return $entry;
}

/** Render one complete grammar entry. */
function renderEntry(array $entry, string $generatedMarker): string
{
    $lines = [
        '# ' . textValue($entry['title']),
        '',
        $generatedMarker,
        '',
    ];

    $tags = array_values(array_filter(
        array_map('textValue', $entry['tags']),
        static fn (string $tag): bool => $tag !== ''
    ));

    if ($tags !== []) {
        $lines[] = '**Tags:** ' . implode(', ', $tags);
        $lines[] = '';
    }

    $lines[] = '## Explanation';
    $lines[] = '';

    foreach ($entry['explanation'] as $section) {
        appendText($lines, textValue($section['heading'] ?? 'Explanation'), $section['text'] ?? '', 3);
        appendNotes($lines, $section['notes'] ?? []);
    }

    $lines[] = '## Forms';
    $lines[] = '';

    foreach ($entry['forms'] as $form) {
        $lines[] = '### ' . textValue($form['label'] ?? 'Form');
        $lines[] = '';

        $structure = textValue($form['structure'] ?? '');

        if ($structure !== '') {
            $lines[] = '**Structure:** ' . $structure;
            $lines[] = '';
        }

        appendExamples($lines, $form['examples'] ?? []);
        appendNotes($lines, $form['notes'] ?? []);
    }

    $lines[] = '## Usage';
    $lines[] = '';

    foreach ($entry['usage'] as $usage) {
        $description = textValue($usage['description'] ?? '');

        if ($description !== '') {
            $lines[] = '### ' . $description;
            $lines[] = '';
        }

        appendExamples($lines, $usage['examples'] ?? []);
        appendNotes($lines, $usage['notes'] ?? []);
    }

    $lines[] = '## Common Mistakes';
    $lines[] = '';

    foreach ($entry['common_mistakes'] as $mistake) {
        $incorrect = textValue($mistake['incorrect'] ?? '');
        $correct = textValue($mistake['correct'] ?? '');
        $explanation = textValue($mistake['explanation'] ?? '');

        if ($incorrect === '' || $correct === '') {
            continue;
        }

        $lines[] = '- **Incorrect:** ' . $incorrect;
        $lines[] = '  **Correct:** ' . $correct;

        if ($explanation !== '') {
            $lines[] = '  **Why:** ' . $explanation;
        }

        $lines[] = '';
    }

    appendNotes($lines, $entry['notes'] ?? [], 'General Notes');

    return rtrim(implode("\n", $lines)) . "\n";
}

if (!is_dir($dataGrammarRoot)) {
    fwrite(STDERR, "Grammar source directory does not exist: {$dataGrammarRoot}\n");
    exit(1);
}

$iterator = new RecursiveIteratorIterator(
    new RecursiveDirectoryIterator($dataGrammarRoot, FilesystemIterator::SKIP_DOTS)
);
$sourceFiles = [];

foreach ($iterator as $fileInfo) {
    if ($fileInfo->isFile() && strtolower($fileInfo->getExtension()) === 'json') {
        $sourceFiles[] = $fileInfo->getPathname();
    }
}

sort($sourceFiles, SORT_STRING);
$entriesByCategory = [];
$expectedOutputFiles = [];
$renderedCount = 0;

try {
    // Validate all source files before writing, preventing partial renders on invalid JSON.
    $entries = [];

    foreach ($sourceFiles as $sourceFile) {
        $json = file_get_contents($sourceFile);

        if ($json === false) {
            throw new RuntimeException("Could not read source file: {$sourceFile}");
        }

        $decoded = json_decode($json, true, 512, JSON_THROW_ON_ERROR);
        $entry = validateEntry($decoded, $sourceFile);
        $relative = substr($sourceFile, strlen($dataGrammarRoot) + 1);
        $segments = explode(DIRECTORY_SEPARATOR, $relative);
        $category = $segments[0];

        if (count($segments) < 2 || !isset($categories[$category])) {
            throw new RuntimeException("Unknown or missing grammar category for: {$sourceFile}");
        }

        $outputFile = $grammarRoot . '/' . basename($relative, '.json') . '.md';
        if (isset($expectedOutputFiles[$outputFile])) {
            throw new RuntimeException("Duplicate grammar output filename: {$outputFile}");
        }

        $expectedOutputFiles[$outputFile] = true;

        $entries[] = [
            'category' => $category,
            'title' => $entry['title'],
            'output' => $outputFile,
            'entry' => $entry,
        ];
    }

    foreach ($entries as $item) {
        if (!writeIfChanged($item['output'], renderEntry($item['entry'], $generatedMarker))) {
            throw new RuntimeException("Could not write rendered page: {$item['output']}");
        }

        $entriesByCategory[$item['category']][] = [
            'title' => $item['title'],
            'output' => $item['output'],
        ];
        $renderedCount++;
    }

    // Remove stale pages only when they carry this script's marker.
    $markdownIterator = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($grammarRoot, FilesystemIterator::SKIP_DOTS)
    );

    foreach ($markdownIterator as $fileInfo) {
        if (!$fileInfo->isFile() || strtolower($fileInfo->getExtension()) !== 'md') {
            continue;
        }

        $path = $fileInfo->getPathname();

        if (isset($expectedOutputFiles[$path])) {
            continue;
        }

        $existing = file_get_contents($path);

        if ($existing === false) {
            throw new RuntimeException("Could not read existing Markdown file: {$path}");
        }

        if (str_contains($existing, $generatedMarker) && !unlink($path)) {
            throw new RuntimeException("Could not remove stale generated page: {$path}");
        }
    }

    // Remove empty category directories left by the previous nested-output layout.
    $directories = [];
    $directoryIterator = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($grammarRoot, FilesystemIterator::SKIP_DOTS),
        RecursiveIteratorIterator::CHILD_FIRST
    );

    foreach ($directoryIterator as $directoryInfo) {
        if ($directoryInfo->isDir()) {
            $directories[] = $directoryInfo->getPathname();
        }
    }

    foreach ($directories as $directory) {
        $remaining = scandir($directory);

        if ($remaining !== false && count($remaining) === 2) {
            rmdir($directory);
        }
    }

    $index = [
        '# Grammar',
        '',
        $generatedMarker,
        '',
        'Automatically generated from the JSON grammar entries in data/grammar/.',
        '',
    ];

    foreach ($categories as $slug => $label) {
        if (empty($entriesByCategory[$slug])) {
            continue;
        }

        $categoryEntries = $entriesByCategory[$slug];

        usort($categoryEntries, static function (array $left, array $right): int {
            $comparison = strcasecmp($left['title'], $right['title']);
            return $comparison !== 0 ? $comparison : strcmp($left['title'], $right['title']);
        });

        $index[] = '## ' . $label;
        $index[] = '';

        foreach ($categoryEntries as $item) {
            $relative = 'grammar/' . basename($item['output']);
            $url = implode('/', array_map('rawurlencode', explode('/', $relative)));
            $title = str_replace(['\\', '[', ']'], ['\\\\', '\\[', '\\]'], $item['title']);
            $index[] = '- [' . $title . '](' . $url . ')';
        }

        $index[] = '';
    }

    if (!writeIfChanged($indexFile, rtrim(implode("\n", $index)) . "\n")) {
        throw new RuntimeException("Could not write grammar index: {$indexFile}");
    }
} catch (JsonException $exception) {
    fwrite(STDERR, "Invalid grammar JSON: {$exception->getMessage()}\n");
    exit(1);
} catch (RuntimeException $exception) {
    fwrite(STDERR, $exception->getMessage() . "\n");
    exit(1);
}

printf(
    "Rendered %d grammar entr%s; grammar.md is up to date.\n",
    $renderedCount,
    $renderedCount === 1 ? 'y' : 'ies'
);
