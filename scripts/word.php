<?php

declare(strict_types=1);

/**
 * Render each data/words/*.json entry to dictionary/<filename>.md,
 * and create a compact alphabetical index in dictionary.md.
 *
 * Run from any working directory:
 *   php scripts/word.php
 */

$root = dirname(__DIR__);
$wordsDirectory = $root . '/data/words';
$dictionaryDirectory = $root . '/dictionary';
$indexFile = $root . '/dictionary.md';
$generatedMarker = '<!-- This file is generated by scripts/word.php. Do not edit it manually. -->';

if (!is_dir($wordsDirectory)) {
    fwrite(STDERR, "Words directory not found: {$wordsDirectory}\n");
    exit(1);
}

$files = glob($wordsDirectory . '/*.json');

if ($files === false) {
    fwrite(STDERR, "Could not read JSON files from: {$wordsDirectory}\n");
    exit(1);
}

$words = [];

foreach ($files as $file) {
    $json = file_get_contents($file);

    if ($json === false) {
        fwrite(STDERR, "Could not read file: {$file}\n");
        exit(1);
    }

    try {
        $entry = json_decode($json, true, 512, JSON_THROW_ON_ERROR);
    } catch (JsonException $exception) {
        fwrite(STDERR, sprintf(
            "Invalid JSON in %s: %s\n",
            $file,
            $exception->getMessage()
        ));
        exit(1);
    }

    if (
        !is_array($entry)
        || ($entry['type'] ?? null) !== 'word'
        || !isset($entry['word'])
        || !is_string($entry['word'])
        || trim($entry['word']) === ''
    ) {
        fwrite(STDERR, "Invalid word entry in: {$file}\n");
        exit(1);
    }

    $entry['_source_slug'] = pathinfo($file, PATHINFO_FILENAME);
    $words[] = $entry;
}

usort($words, static function (array $left, array $right): int {
    $comparison = strcasecmp($left['word'], $right['word']);

    return $comparison !== 0
        ? $comparison
        : strcmp($left['word'], $right['word']);
});

/**
 * Write a generated file only when its contents differ.
 *
 * Avoids unnecessary disk writes while preserving unchanged files and mtimes.
 */
function writeIfChanged(string $path, string $content): bool
{
    if (is_file($path)) {
        $existingContent = file_get_contents($path);

        if ($existingContent === false) {
            fwrite(STDERR, "Could not read existing file: {$path}\n");
            return false;
        }

        if ($existingContent === $content) {
            return true;
        }
    }

    return file_put_contents($path, $content, LOCK_EX) !== false;
}

/**
 * Keep JSON content safe to embed in a Markdown line.
 */
function markdownText(string $value): string
{
    return str_replace(
        ["\\", '|', "\r", "\n"],
        ["\\\\", '\\|', ' ', ' '],
        trim($value)
    );
}

/**
 * Format a scalar or nested scalar value for the grammar summary.
 */
function grammarValue(mixed $value): string
{
    if (is_bool($value)) {
        return $value ? 'yes' : 'no';
    }

    if (is_scalar($value) || $value === null) {
        return (string) $value;
    }

    if (is_array($value)) {
        return implode(', ', array_map(
            static fn (mixed $item): string => is_scalar($item) || $item === null
                ? (string) $item
                : (string) json_encode($item, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES),
            $value
        ));
    }

    return '';
}

/**
 * Render a grammar object as a compact inline list.
 */
function renderGrammar(mixed $grammar): string
{
    if (!is_array($grammar) || $grammar === []) {
        return '';
    }

    $items = [];

    foreach ($grammar as $key => $value) {
        $formattedValue = grammarValue($value);

        if ($formattedValue !== '') {
            $items[] = markdownText((string) $key) . ': ' . markdownText($formattedValue);
        }
    }

    return implode('; ', $items);
}

/**
 * Render a list of strings as a Markdown bullet list.
 */
function renderBulletList(array $items): string
{
    $lines = [];

    foreach ($items as $item) {
        if (is_string($item) && trim($item) !== '') {
            $lines[] = '- ' . markdownText($item);
        }
    }

    return implode("\n", $lines);
}

/**
 * Render one word entry using the existing detailed dictionary layout.
 */
function renderWord(array $word, string $generatedMarker): string
{
    $markdown = [
        '# ' . markdownText($word['word']),
        '',
        $generatedMarker,
        '',
    ];

    $pronunciation = $word['pronunciation']['uk'] ?? '';
    $tags = is_array($word['tags'] ?? null) ? $word['tags'] : [];

    if (is_string($pronunciation) && trim($pronunciation) !== '') {
        $markdown[] = '**Pronunciation (UK):** ' . markdownText($pronunciation);
        $markdown[] = '';
    }

    if ($tags !== []) {
        $markdown[] = '**Tags:** ' . implode(', ', array_map(
            static fn (mixed $tag): string => is_string($tag) ? markdownText($tag) : '',
            $tags
        ));
        $markdown[] = '';
    }

    foreach (($word['parts_of_speech'] ?? []) as $part) {
        if (!is_array($part)) {
            continue;
        }

        $partOfSpeech = $part['part_of_speech'] ?? 'Other';
        $markdown[] = '## ' . ucfirst(markdownText(is_string($partOfSpeech) ? $partOfSpeech : 'Other'));
        $markdown[] = '';

        $grammar = renderGrammar($part['grammar'] ?? []);

        if ($grammar !== '') {
            $markdown[] = '**Grammar:** ' . $grammar;
            $markdown[] = '';
        }

        foreach (($part['meanings'] ?? []) as $index => $meaning) {
            if (!is_array($meaning)) {
                continue;
            }

            $definition = $meaning['meaning'] ?? '';

            if (!is_string($definition) || trim($definition) === '') {
                continue;
            }

            $markdown[] = '### Meaning ' . ($index + 1);
            $markdown[] = markdownText($definition);
            $markdown[] = '';

            $meaningGrammar = renderGrammar($meaning['grammar'] ?? []);

            if ($meaningGrammar !== '') {
                $markdown[] = '**Grammar:** ' . $meaningGrammar;
                $markdown[] = '';
            }

            foreach (($meaning['examples'] ?? []) as $example) {
                if (is_string($example) && trim($example) !== '') {
                    $markdown[] = '> ' . markdownText($example);
                    $markdown[] = '';
                }
            }

            foreach ([
                'synonyms' => 'Synonyms',
                'antonyms' => 'Antonyms',
                'collocations' => 'Collocations',
                'patterns' => 'Patterns',
                'notes' => 'Notes',
            ] as $field => $label) {
                $items = $meaning[$field] ?? [];

                if (is_array($items) && $items !== []) {
                    $list = renderBulletList($items);

                    if ($list !== '') {
                        $markdown[] = '**' . $label . ':**';
                        $markdown[] = $list;
                        $markdown[] = '';
                    }
                }
            }
        }

        $partNotes = $part['notes'] ?? [];

        if (is_array($partNotes) && $partNotes !== []) {
            $list = renderBulletList($partNotes);

            if ($list !== '') {
                $markdown[] = '**Part-of-speech notes:**';
                $markdown[] = $list;
                $markdown[] = '';
            }
        }
    }

    foreach (['related' => 'Related words', 'notes' => 'General notes'] as $field => $label) {
        $items = $word[$field] ?? [];

        if (is_array($items) && $items !== []) {
            $list = renderBulletList($items);

            if ($list !== '') {
                $markdown[] = '## ' . $label;
                $markdown[] = '';
                $markdown[] = $list;
                $markdown[] = '';
            }
        }
    }

    return rtrim(implode("\n", $markdown)) . "\n";
}

if (!is_dir($dictionaryDirectory) && !mkdir($dictionaryDirectory, 0775, true) && !is_dir($dictionaryDirectory)) {
    fwrite(STDERR, "Could not create dictionary directory: {$dictionaryDirectory}\n");
    exit(1);
}

$expectedFiles = [];
$index = [
    '# English Word Dictionary',
    '',
    $generatedMarker,
    '',
    '| Word |',
    '| --- |',
];

foreach ($words as $word) {
    $slug = $word['_source_slug'];
    $relativePath = 'dictionary/' . $slug . '.md';
    $outputPath = $root . '/' . $relativePath;
    $expectedFiles[] = $outputPath;

    $content = renderWord($word, $generatedMarker);

    if (!writeIfChanged($outputPath, $content)) {
        fwrite(STDERR, "Could not write dictionary page: {$outputPath}\n");
        exit(1);
    }

    $link = 'dictionary/' . rawurlencode($slug) . '.md';
    $index[] = '| [' . markdownText($word['word']) . '](' . $link . ') |';
}

$indexContent = rtrim(implode("\n", $index)) . "\n";

if (!writeIfChanged($indexFile, $indexContent)) {
    fwrite(STDERR, "Could not write dictionary index: {$indexFile}\n");
    exit(1);
}

/**
 * Remove only stale pages previously generated by this script.
 * Hand-written Markdown files in dictionary/ are left untouched.
 */
foreach (glob($dictionaryDirectory . '/*.md') ?: [] as $existingFile) {
    if (in_array($existingFile, $expectedFiles, true)) {
        continue;
    }

    $existingContent = file_get_contents($existingFile);

    if ($existingContent !== false && str_contains($existingContent, $generatedMarker)) {
        if (!unlink($existingFile)) {
            fwrite(STDERR, "Could not remove stale dictionary page: {$existingFile}\n");
            exit(1);
        }
    }
}

printf(
    "Rendered %d word page%s and updated %s\n",
    count($words),
    count($words) === 1 ? '' : 's',
    $indexFile
);
